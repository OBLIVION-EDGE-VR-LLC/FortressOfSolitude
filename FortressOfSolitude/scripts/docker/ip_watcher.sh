#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════
#  ip_watcher.sh — Dynamic IP ban daemon for FortressOfSolitude
#
#  Runs as a background process inside the container.
#  Every 30 seconds it:
#    1. Reads the NGINX access log
#    2. Counts requests per IP in the last 60 seconds
#    3. If any IP exceeds BAN_THRESHOLD, adds it to the dynamic blocklist
#    4. Reloads NGINX to pick up the new blocklist
#    5. Logs the ban event
#
#  Bans are temporary — they expire after BAN_DURATION minutes.
#  Whitelisted IPs are never banned.
#
#  1337_TECH DBA, Austin Texas - 2026
# ═══════════════════════════════════════════════════════════════════

# -- Config --
BAN_THRESHOLD="${BAN_THRESHOLD:-60}"         # Requests per minute to trigger ban
BAN_DURATION="${BAN_DURATION:-30}"           # Minutes to keep an IP banned
CHECK_INTERVAL=30                             # Seconds between checks
ACCESS_LOG="/var/log/nginx/access.log"
BLOCKLIST="/etc/nginx/conf.d/dynamic_blocklist.conf"
BAN_LOG="/var/log/nginx/banned_ips.log"
BAN_DB="/tmp/fortress_bans.txt"              # IP|ban_timestamp

# -- Whitelist: never ban these IPs --
# Add your own IP(s) here
WHITELIST=(
    "127.0.0.1"
    "::1"
    # Add your residential IPs:
    # "76.186.213.63"
)

log() { echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] $*" | tee -a "$BAN_LOG"; }

# Initialize files
mkdir -p /etc/nginx/conf.d
touch "$BLOCKLIST" "$BAN_LOG" "$BAN_DB"

is_whitelisted() {
    local ip="$1"
    for wl in "${WHITELIST[@]}"; do
        [[ "$ip" == "$wl" ]] && return 0
    done
    return 1
}

# ── Expire old bans ────────────────────────────────────────────
expire_bans() {
    local NOW
    NOW="$(date +%s)"
    local DURATION_SECS=$(( BAN_DURATION * 60 ))
    local CHANGED=false

    if [[ ! -s "$BAN_DB" ]]; then return; fi

    local TEMP
    TEMP="$(mktemp)"
    while IFS='|' read -r ip ts; do
        local AGE=$(( NOW - ts ))
        if [[ $AGE -lt $DURATION_SECS ]]; then
            echo "${ip}|${ts}" >> "$TEMP"
        else
            log "UNBAN: ${ip} (expired after ${BAN_DURATION}m)"
            CHANGED=true
        fi
    done < "$BAN_DB"

    mv "$TEMP" "$BAN_DB"

    if [[ "$CHANGED" == "true" ]]; then
        rebuild_blocklist
    fi
}

# ── Rebuild the NGINX blocklist from ban DB ─────────────────────
rebuild_blocklist() {
    local TEMP
    TEMP="$(mktemp)"
    echo "# Dynamic blocklist — auto-generated by ip_watcher.sh" > "$TEMP"
    echo "# Last updated: $(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$TEMP"

    if [[ -s "$BAN_DB" ]]; then
        while IFS='|' read -r ip ts; do
            echo "deny ${ip};" >> "$TEMP"
        done < "$BAN_DB"
    fi

    mv "$TEMP" "$BLOCKLIST"
    nginx -s reload 2>/dev/null || true
}

# ── Check for hammering IPs ─────────────────────────────────────
check_hammers() {
    if [[ ! -f "$ACCESS_LOG" ]]; then return; fi

    local NOW
    NOW="$(date +%s)"
    local ONE_MIN_AGO=$(( NOW - 60 ))

    # Get the current minute's log entries and count per IP
    # Using the timestamp from the log: [15/Oct/2026:14:30:00 +0000]
    # Simpler approach: just count the last N lines (roughly 1 minute's worth)
    local LINES
    LINES="$(wc -l < "$ACCESS_LOG" 2>/dev/null || echo 0)"

    # Read the last 500 lines (more than enough for 1 minute window)
    local TAIL_LINES=500
    [[ "$LINES" -lt "$TAIL_LINES" ]] && TAIL_LINES="$LINES"

    if [[ "$TAIL_LINES" -eq 0 ]]; then return; fi

    # Count requests per IP in recent lines
    # Filter to only lines from the last 60 seconds
    tail -n "$TAIL_LINES" "$ACCESS_LOG" | \
        awk -v threshold="$BAN_THRESHOLD" '
        {
            ip = $1
            count[ip]++
        }
        END {
            for (ip in count) {
                if (count[ip] >= threshold) {
                    print ip, count[ip]
                }
            }
        }
    ' | while read -r ip count; do
        # Skip whitelisted
        if is_whitelisted "$ip"; then
            continue
        fi

        # Skip already banned
        if grep -q "^${ip}|" "$BAN_DB" 2>/dev/null; then
            continue
        fi

        # BAN IT
        log "BAN: ${ip} — ${count} requests in window (threshold: ${BAN_THRESHOLD})"
        echo "${ip}|${NOW}" >> "$BAN_DB"
        rebuild_blocklist
    done

    # Also check the rate-limited log for repeat offenders
    if [[ -f "/var/log/nginx/ratelimited.log" ]]; then
        tail -n 100 /var/log/nginx/ratelimited.log 2>/dev/null | \
            awk '{print $1}' | sort | uniq -c | sort -rn | \
            while read -r count ip; do
                if [[ "$count" -gt 10 ]] && ! is_whitelisted "$ip" && ! grep -q "^${ip}|" "$BAN_DB" 2>/dev/null; then
                    log "BAN (rate-limit repeat): ${ip} — ${count} rate-limited requests"
                    echo "${ip}|${NOW}" >> "$BAN_DB"
                    rebuild_blocklist
                fi
            done
    fi
}

# ── Main loop ───────────────────────────────────────────────────
log "IP watcher started (threshold: ${BAN_THRESHOLD} req/min, ban duration: ${BAN_DURATION}m)"

# Create initial empty blocklist so NGINX can start
if [[ ! -f "$BLOCKLIST" ]]; then
    echo "# Dynamic blocklist — auto-generated by ip_watcher.sh" > "$BLOCKLIST"
fi

while true; do
    expire_bans
    check_hammers
    sleep "$CHECK_INTERVAL"
done
